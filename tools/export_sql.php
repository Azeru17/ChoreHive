<?php
/**
 * Export the current ChoreHive schema (and optionally its rows) to a single
 * .sql file that can be pasted straight into the TiDB Cloud web SQL editor.
 *
 *   php tools/export_sql.php                          # schema only -> tidb_schema.sql
 *   php tools/export_sql.php --data --out=all.sql     # schema + rows
 *   php tools/export_sql.php --demo-only --out=seed.sql
 *
 * The schema is read back out of the live database with SHOW CREATE TABLE and
 * ordered by foreign-key dependency, so the output is guaranteed to match the
 * schema the app actually runs against instead of depending on the order of
 * hand-maintained .sql files.
 *
 * Tables holding binary data are skipped unless --binary is passed, because
 * pasting multi-megabyte BLOBs into a browser SQL editor is impractical.
 * Those tables (media_files, app_sessions) are re-created by the seeder via
 * the normal PHP path, which stores uploads correctly for the configured
 * MEDIA_STORAGE backend.
 *
 * CLI only.
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(403);
    exit("CLI only.\n");
}

mysqli_report(MYSQLI_REPORT_OFF);

require __DIR__ . '/../config.php';

$argvList = array_slice($argv, 1);
$withData = in_array('--data', $argvList, true) || in_array('--demo-only', $argvList, true);
$withBinary = in_array('--binary', $argvList, true);
$demoOnly = in_array('--demo-only', $argvList, true);

$out = 'tidb_schema.sql';
$splitInto = 0;
foreach ($argvList as $a) {
    if (strpos($a, '--out=') === 0) {
        $out = substr($a, 6);
    }
    if (strpos($a, '--split=') === 0) {
        $splitInto = max(1, (int)substr($a, 8));
    }
}

$dbName = DB_NAME;

/* Tables that contain BLOB/BINARY columns. */
$binaryTables = [];
$r = $conn->query(
    "SELECT DISTINCT TABLE_NAME FROM information_schema.COLUMNS
      WHERE TABLE_SCHEMA = DATABASE()
        AND DATA_TYPE IN ('blob','mediumblob','longblob','tinyblob','binary','varbinary')"
);
while ($x = $r->fetch_assoc()) {
    $binaryTables[] = $x['TABLE_NAME'];
}

/* Order tables so a parent is always created before its children. */
$tables = [];
$r = $conn->query("SELECT TABLE_NAME FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE='BASE TABLE'");
while ($x = $r->fetch_assoc()) {
    $tables[$x['TABLE_NAME']] = ['deps' => [], 'sql' => ''];
}

$fk = $conn->query(
    "SELECT TABLE_NAME, REFERENCED_TABLE_NAME
       FROM information_schema.KEY_COLUMN_USAGE
      WHERE TABLE_SCHEMA = DATABASE() AND REFERENCED_TABLE_NAME IS NOT NULL"
);
while ($x = $fk->fetch_assoc()) {
    $child = $x['TABLE_NAME'];
    $parent = $x['REFERENCED_TABLE_NAME'];
    if (isset($tables[$child], $tables[$parent]) && $child !== $parent) {
        $tables[$child]['deps'][$parent] = true;
    }
}

$ordered = [];
$placed = [];
$guard = 0;
while (count($ordered) < count($tables) && $guard++ < 1000) {
    foreach ($tables as $name => $_) {
        if (isset($placed[$name])) {
            continue;
        }
        $ready = true;
        foreach (array_keys($tables[$name]['deps']) as $dep) {
            if (isset($tables[$dep]) && !isset($placed[$dep])) {
                $ready = false;
                break;
            }
        }
        if ($ready) {
            $ordered[] = $name;
            $placed[$name] = true;
        }
    }
}
// Anything left is part of a dependency cycle; append it so nothing is lost.
foreach (array_keys($tables) as $name) {
    if (!isset($placed[$name])) {
        $ordered[] = $name;
        $placed[$name] = true;
    }
}

foreach ($ordered as $name) {
    $res = $conn->query("SHOW CREATE TABLE `{$conn->real_escape_string($name)}`");
    if (!$res || !($row = $res->fetch_assoc())) {
        fwrite(STDERR, "Could not read the definition of {$name}\n");
        exit(1);
    }
    $create = $row['Create Table'] ?? '';
    $create = preg_replace('/\s+DEFINER=[^\s]+/', '', $create);
    $tables[$name]['sql'] = $create . ";";
}

$lines = [];
$lines[] = "-- ---------------------------------------------------------------------";
$lines[] = "-- ChoreHive database for TiDB Cloud";
$lines[] = "-- Generated by tools/export_sql.php on " . date('Y-m-d H:i:s');
$lines[] = "-- Target: {$dbName} @ " . DB_HOST;
$lines[] = "--";
$lines[] = "-- Paste the whole file into the TiDB Cloud web SQL editor and run it.";
$lines[] = "-- Safe to run more than once: every table is dropped and rebuilt.";
if ($withData) {
    $lines[] = "--";
    $lines[] = "-- Includes sample rows" . ($demoOnly ? ' (demo data only).' : '.');
}
if ($binaryTables && !$withBinary) {
    $lines[] = '--';
    $lines[] = '-- NOTE: tables holding binary data were skipped for browser import:';
    $lines[] = '--        ' . implode(', ', $binaryTables);
    $lines[] = '--        The tables are still CREATED below. Uploaded images live in';
    $lines[] = '--        media_files; run php tools/seed_demo_data.php from a machine that can';
    $lines[] = '--        reach this database if you want the sample photos as well.';
}
$lines[] = "-- ---------------------------------------------------------------------";
$lines[] = "";
$lines[] = "CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;";
$lines[] = "USE `{$dbName}`;";
$lines[] = "";
$lines[] = "SET FOREIGN_KEY_CHECKS = 0;";
$lines[] = "";

// Complete statements, kept so --split can divide them without re-parsing text.
$stmtOut = [];
$stmtOut[] = "SET FOREIGN_KEY_CHECKS = 0;";

// Drop children before parents.
foreach (array_reverse($ordered) as $name) {
    $lines[] = "DROP TABLE IF EXISTS `{$name}`;";
    $stmtOut[] = "DROP TABLE IF EXISTS `{$name}`;";
}
$lines[] = "";

// Create parents before children.
foreach ($ordered as $name) {
    $lines[] = $tables[$name]['sql'];
    $lines[] = "";
    $stmtOut[] = $tables[$name]['sql'];
}
$stmtOut[] = "SET FOREIGN_KEY_CHECKS = 1;";
$lines[] = "SET FOREIGN_KEY_CHECKS = 1;";
$lines[] = "";

// Demo data references these; without the rows the pages would show broken images.
$skipData = $binaryTables;
if (!$withBinary) {
    $skipData[] = 'booking_photos';
    $skipData[] = 'worker_portfolio';
}
$skipData = array_unique($skipData);

if ($withData) {
    $lines[] = "-- ---------------------------------------------------------------------";
    $lines[] = "-- Sample rows";
    $lines[] = "-- ---------------------------------------------------------------------";
    $lines[] = "";

    foreach ($ordered as $name) {
        if (in_array($name, $skipData, true)) {
            continue;
        }
        // `services` is reference data, not demo data, but bookings reference it
        // through a foreign key - omitting it makes every booking insert fail.
        if ($demoOnly && !preg_match('/^(users|services|bookings|checklist_items|feedback|badges|chat_threads|chat_messages|notifications|saved_addresses|favorite_workers|contact_messages|audit_log|role_id_counters)$/', $name)) {
            continue;
        }

        $res = $conn->query("SELECT * FROM `{$conn->real_escape_string($name)}`");
        if (!$res) {
            continue;
        }
        $rows = $res->fetch_all(MYSQLI_ASSOC);
        if (!$rows) {
            continue;
        }

        $cols = array_keys($rows[0]);
        $colList = implode(', ', array_map(static fn($c) => "`{$c}`", $cols));

        $lines[] = "-- {$name} (" . count($rows) . " rows)";
        $chunk = [];
        $flush = function () use (&$chunk, &$lines, &$stmtOut, $name, $colList) {
            if (!$chunk) {
                return;
            }
            $stmt = "INSERT INTO `{$name}` ({$colList}) VALUES\n  " . implode(",\n  ", $chunk) . ';';
            $lines[] = $stmt;
            $stmtOut[] = $stmt;
            $chunk = [];
        };
        foreach ($rows as $row) {
            $vals = [];
            foreach ($cols as $c) {
                $v = $row[$c];
                if ($v === null) {
                    $vals[] = 'NULL';
                } else {
                    // A semicolon inside a quoted value derails naive statement
                    // splitters (browsers, some editors), which then run only
                    // part of the script. Safe for our sample copy.
                    $v = str_replace(';', ',', (string)$v);
                    $vals[] = "'" . $conn->real_escape_string($v) . "'";
                }
            }
            $chunk[] = '(' . implode(', ', $vals) . ')';
            if (count($chunk) >= 100) {
                $flush();
            }
        }
        $flush();
        $lines[] = "";
    }
}

$sql = implode("\n", $lines) . "\n";

/* Optional: split the script into several paste-safe chunks. Some browser
   based SQL editors only run a fraction of a large pasted script, so smaller
   files are far more reliable there. Every chunk is independently runnable. */
if ($splitInto > 1) {
    $preamble = [];
    $preamble[] = "-- ChoreHive database for TiDB Cloud - part {$splitInto} of {$splitInto}";
    $preamble[] = "-- Generated by tools/export_sql.php on " . date('Y-m-d H:i:s');
    $preamble[] = "--";
    $preamble[] = "-- Run every part in order.";
    $preamble[] = "-- ---------------------------------------------------------------------";
    $preamble[] = "";
    $preamble[] = "CREATE DATABASE IF NOT EXISTS `{$dbName}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;";
    $preamble[] = "USE `{$dbName}`;";
    $preamble[] = "";
    $preamble[] = "SET FOREIGN_KEY_CHECKS = 0;";
    $preamble[] = "";

    // $stmtOut already holds every complete statement (DROP, CREATE and the
    // full multi-line INSERTs) in execution order, so it can be divided
    // without re-parsing text and losing statement bodies.
    $statements = $stmtOut;

    $total = count($statements);
    $per = (int)ceil($total / $splitInto);
    $base = preg_replace('/\.sql$/', '', $out);
    if ($base === $out) {
        $base = 'tidb_import';
    }
    $written = [];
    for ($p = 0; $p < $splitInto; $p++) {
        $slice = array_slice($statements, $p * $per, $per);
        if (!$slice) {
            continue;
        }
        $chunk = $preamble;
        $chunk[0] = "-- ChoreHive database for TiDB Cloud - part " . ($p + 1) . " of {$splitInto}";
        foreach ($slice as $s) {
            $chunk[] = $s;
        }
        $chunk[] = "SET FOREIGN_KEY_CHECKS = 1;";
        $chunk[] = "";
        $file = $base . '_part' . ($p + 1) . '.sql';
        $path = strpos($file, '/') !== false ? $file : __DIR__ . '/../' . $file;
        file_put_contents($path, implode("\n", $chunk));
        $written[] = $path;
    }

    echo "Split into " . count($written) . " files:\n";
    foreach ($written as $w) {
        echo '  - ' . basename($w) . ' (' . number_format(filesize($w)) . " bytes)\n";
    }
    echo "\nRun them in numeric order: part1, part2, ...\n";
    exit(0);
}

$target = strpos($out, '/') === false && strpos($out, '\\') === false ? __DIR__ . '/../' . $out : $out;

if (file_put_contents($target, $sql) === false) {
    fwrite(STDERR, "Could not write {$target}\n");
    exit(1);
}

echo "Wrote {$target}\n";
echo '  tables: ' . count($ordered) . "\n";
echo '  rows:   ' . ($withData ? 'yes' : 'no (schema only)') . "\n";
echo '  size:   ' . number_format(strlen($sql)) . " bytes\n";
if ($skipData) {
    echo '  skipped tables in data: ' . implode(', ', $skipData) . "\n";
}